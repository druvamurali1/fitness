// Plain-English versions of the notation used in the plan.
export function setsText(e) {
  const unit = e.measure === 'seconds' ? 'seconds' : 'reps';
  const sets = `${e.sets} set${e.sets === 1 ? '' : 's'}`;
  if (e.repMin == null) return sets;
  return `${sets} of ${e.repMin} to ${e.repMax} ${unit}`;
}
